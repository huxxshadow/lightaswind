"""Render the in-game credit portraits (the main menu room's cast posters) as the website's team-card pictures.

The game keeps each portrait as a small grid of colours in
Main/Assets/_Project/Runtime/OceanWorld/Menu/Items/RoomGamePosterArt.cs (generated by Main/Tools/ui/menu_posters.py).
This reads that file (read-only) and writes assets/img/cast-<name>.png, each cell blown up to a square block so the
pixel art stays crisp.

    python tools/cast_portraits.py
"""
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT.parent / "Main" / "Assets" / "_Project" / "Runtime" / "OceanWorld" / "Menu" / "Items" / "RoomGamePosterArt.cs"
OUT = ROOT / "assets" / "img"
CELL = 10  # px per grid cell

src = ART.read_text(encoding="utf-8")
entry = re.compile(r'\("(cast\.[a-z]+)",\s*(\d+),\s*(\d+),\s*((?:"[0-9a-f]*"\s*\+?\s*)+)\)', re.S)
found = 0
for name, w, h, body in entry.findall(src):
    w, h = int(w), int(h)
    hexs = "".join(re.findall(r'"([0-9a-f]*)"', body))
    assert len(hexs) == 6 * w * h, (name, len(hexs), w, h)
    im = Image.new("RGB", (w, h))
    im.putdata([tuple(int(hexs[6 * k + c * 2: 6 * k + c * 2 + 2], 16) for c in range(3)) for k in range(w * h)])
    out = OUT / f"cast-{name.split('.')[1]}.png"
    im.resize((w * CELL, h * CELL), Image.NEAREST).save(out, optimize=True)
    found += 1
    print(name, f"{w}x{h}", "->", out.name, out.stat().st_size, "bytes")
assert found == 5, f"expected 5 cast portraits, found {found}"
